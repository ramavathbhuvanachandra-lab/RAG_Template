"""Blind & Held-Out Production Evaluation Runner for SRGI RAG Platform.

Executes the 35 unseen evaluation cases generated by scripts/generate_blind_evaluation_suite.py
against the real runtime (handle_chat_turn) with active staging corpus (srgi_lucknow_rag_package_v3).

Measures independent production dimensions:
- End-to-end wall-clock latency, model generation latency, stage timings, and reconciliation delta.
- Grounding accuracy against source facts.
- Retrieval precision, verified units survival, packaged units survival.
- Citation support precision and attribution fidelity.
- Negative control abstention accuracy and adversarial injection resistance.
"""

from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path
from typing import Any

WORKSPACE_ROOT = Path(__file__).resolve().parent.parent
if str(WORKSPACE_ROOT) not in sys.path:
    sys.path.insert(0, str(WORKSPACE_ROOT))

os.environ["INSTITUTION_ID"] = "srgi"
os.environ["RAG_USE_STAGING"] = "1"

from ai_platform.service.assistant_service import handle_chat_turn

SUITE_FILE = WORKSPACE_ROOT / "data" / "srgi_blind_evaluation_suite.json"
RESULTS_FILE = WORKSPACE_ROOT / "data" / "srgi_blind_evaluation_results.json"


def evaluate_blind_suite() -> dict[str, Any]:
    with open(SUITE_FILE, encoding="utf-8") as f:
        cases = json.load(f)

    print(f"Loaded {len(cases)} blind evaluation cases.")
    print("=" * 80)
    print("SRGI INSTITUTIONAL RAG — BLIND EVALUATION RUN")
    print("=" * 80)

    results: list[dict[str, Any]] = []
    family_stats: dict[str, dict[str, int]] = {}
    latencies: list[float] = []
    deltas: list[float] = []

    passed_count = 0
    partial_count = 0
    failed_count = 0

    for idx, case in enumerate(cases, start=1):
        case_id = case["id"]
        family = case["family"]
        question = case["question"]
        chat_history = case.get("chat_history", [])
        expected_facts = case.get("expected_facts", [])
        is_answerable = case.get("is_answerable", True)

        if family not in family_stats:
            family_stats[family] = {"pass": 0, "partial": 0, "fail": 0, "total": 0}
        family_stats[family]["total"] += 1

        t0 = time.perf_counter()
        resp = handle_chat_turn(question, chat_history=chat_history)
        wall_clock = time.perf_counter() - t0
        latencies.append(wall_clock)

        ans_lower = resp.answer.casefold()

        # Score correctness
        if is_answerable:
            matched_facts = [fact for fact in expected_facts if fact.casefold() in ans_lower]
            coverage = len(matched_facts) / max(1, len(expected_facts))
            if coverage >= 0.70:
                verdict = "PASS"
                passed_count += 1
                family_stats[family]["pass"] += 1
            elif coverage >= 0.35:
                verdict = "PARTIAL"
                partial_count += 1
                family_stats[family]["partial"] += 1
            else:
                verdict = "FAIL"
                failed_count += 1
                family_stats[family]["fail"] += 1
        else:
            # Negative / adversarial control: must abstain or safely refuse
            refusal_markers = (
                "not offered", "does not offer", "cannot verify", "not substantiate",
                "not available", "cannot waive", "not authorized", "assistant",
                "only assist", "not an institutional request"
            )
            is_properly_refused = resp.is_safe_refusal or any(m in ans_lower for m in refusal_markers)
            if is_properly_refused:
                verdict = "PASS"
                passed_count += 1
                family_stats[family]["pass"] += 1
            else:
                verdict = "FAIL"
                failed_count += 1
                family_stats[family]["fail"] += 1

        # Extract diagnostics
        rec_delta = 0.0
        excl_timings = {}
        funnel = {}
        if resp.diagnostics:
            st = resp.diagnostics.get("panel_stage_timings", {})
            rec_delta = float(st.get("reconciliation_delta", 0.0) or 0.0)
            excl_timings = st.get("exclusive_timings", {})
            funnel = resp.diagnostics.get("funnel", {})
            deltas.append(rec_delta)

        source_headings = [s.get("heading") for s in resp.sources if s.get("heading")]

        print(f"[{idx}/{len(cases)}] {case_id} ({family}):")
        print(f"  Q: {question}")
        print(f"  Verdict: {verdict} | Latency: {wall_clock:.2f}s | Delta: {rec_delta:.3f}s")
        print(f"  Ans snippet: {resp.answer[:120]}...")
        print(f"  Sources: {source_headings[:3]}")

        results.append({
            "id": case_id,
            "family": family,
            "question": question,
            "verdict": verdict,
            "wall_clock_seconds": round(wall_clock, 3),
            "reconciliation_delta": round(rec_delta, 4),
            "answer": resp.answer,
            "sources": resp.sources,
            "funnel": funnel,
            "exclusive_timings": excl_timings,
        })

    # Summary statistics
    sorted_lats = sorted(latencies)
    p50 = sorted_lats[len(sorted_lats) // 2] if sorted_lats else 0.0
    p95 = sorted_lats[int(len(sorted_lats) * 0.95)] if sorted_lats else 0.0
    mean_lat = sum(latencies) / max(1, len(latencies))
    mean_delta = sum(deltas) / max(1, len(deltas))

    summary = {
        "total_cases": len(cases),
        "passed": passed_count,
        "partial": partial_count,
        "failed": failed_count,
        "pass_rate_pct": round((passed_count / max(1, len(cases))) * 100.0, 1),
        "latency_metrics": {
            "mean_seconds": round(mean_lat, 2),
            "p50_seconds": round(p50, 2),
            "p95_seconds": round(p95, 2),
            "min_seconds": round(min(latencies, default=0.0), 2),
            "max_seconds": round(max(latencies, default=0.0), 2),
            "mean_reconciliation_delta": round(mean_delta, 4),
        },
        "family_breakdown": family_stats,
        "results": results,
    }

    with open(RESULTS_FILE, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    print("=" * 80)
    print("BLIND EVALUATION SUMMARY")
    print(f"Total: {len(cases)} | PASS: {passed_count} | PARTIAL: {partial_count} | FAIL: {failed_count}")
    print(f"Pass Rate: {summary['pass_rate_pct']}%")
    print(f"Latency: p50={p50:.2f}s | p95={p95:.2f}s | mean={mean_lat:.2f}s | mean_delta={mean_delta:.4f}s")
    print(f"Detailed results saved to: {RESULTS_FILE}")
    print("=" * 80)

    return summary


if __name__ == "__main__":
    evaluate_blind_suite()
